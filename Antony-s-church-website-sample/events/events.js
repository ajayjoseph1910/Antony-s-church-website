const originalText = new WeakMap();

function setLanguage(language) {
    const tamil = language === "ta";
    const walker = document.createTreeWalker(
        document.querySelector(".page-content"),
        NodeFilter.SHOW_TEXT
    );

    let node;

    while ((node = walker.nextNode())) {
        if (!node.nodeValue.trim()) continue;

        if (!originalText.has(node)) {
            originalText.set(node, node.nodeValue);
        }

        const original = originalText.get(node);
        const key = original.replace(/\s+/g, " ").trim();

        if (tamil && translations[key]) {
            node.nodeValue = original.replace(key, translations[key]);
        } else {
            node.nodeValue = original;
        }
    }

    document.documentElement.lang = tamil ? "ta" : "en";

    document.getElementById("englishBtn").classList.toggle("active", !tamil);
    document.getElementById("tamilBtn").classList.toggle("active", tamil);

    localStorage.setItem("churchLanguage", language);
}

document.getElementById("englishBtn").addEventListener("click", () => {
    setLanguage("en");
});

document.getElementById("tamilBtn").addEventListener("click", () => {
    setLanguage("ta");
});

const savedLanguage = localStorage.getItem("churchLanguage") || "en";
setLanguage(savedLanguage);
