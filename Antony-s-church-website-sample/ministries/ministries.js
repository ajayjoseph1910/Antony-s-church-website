const englishBtn = document.getElementById("englishBtn");
const tamilBtn = document.getElementById("tamilBtn");

/* Keep the original English text so users can switch back */
const originalText = new WeakMap();

function normalizeText(text) {
    return text.replace(/\s+/g, " ").trim();
}

function translatePage(language) {
    const walker = document.createTreeWalker(
        document.querySelector(".page-content"),
        NodeFilter.SHOW_TEXT
    );

    const textNodes = [];
    let node;

    while ((node = walker.nextNode())) {
        if (node.parentElement.closest(".language-switch")) continue;
        if (!normalizeText(node.nodeValue)) continue;
        textNodes.push(node);
    }

    textNodes.forEach((textNode) => {
        if (!originalText.has(textNode)) {
            originalText.set(textNode, textNode.nodeValue);
        }

        const original = originalText.get(textNode);
        const key = normalizeText(original);

        if (language === "ta" && ministryTranslations[key]) {
            const leadingSpace = original.match(/^\s*/)?.[0] || "";
            const trailingSpace = original.match(/\s*$/)?.[0] || "";

            textNode.nodeValue =
                leadingSpace + ministryTranslations[key] + trailingSpace;
        } else {
            textNode.nodeValue = original;
        }
    });

    document.documentElement.lang = language;

    englishBtn.classList.toggle("active", language === "en");
    tamilBtn.classList.toggle("active", language === "ta");

    try {
        localStorage.setItem("churchLanguage", language);
    } catch (error) {
        // Language switching still works if storage is unavailable.
    }
}

englishBtn.addEventListener("click", () => translatePage("en"));
tamilBtn.addEventListener("click", () => translatePage("ta"));

let savedLanguage = "en";

try {
    savedLanguage = localStorage.getItem("churchLanguage") || "en";
} catch (error) {
    savedLanguage = "en";
}

translatePage(savedLanguage === "ta" ? "ta" : "en");
